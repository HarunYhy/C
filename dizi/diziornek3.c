//N elamanlı bir dizide en büyük ve en küçük elamanı bulan programı yaz
#include <stdio.h>
#define N 5
int a[N]={4,6,2,78,15};
int buyuk, guccuk;
void main()
{
   guccuk=a[0];
   buyuk=a[0];
   for (int i = 1; i < N; i++)
   {
      if (a[i]>buyuk)
      {
         buyuk=a[i];
      }
      else if (a[i]<guccuk)
      {
         guccuk=a[i];
      }
      
   }

   printf("en kücük %d \nen büyük %d", guccuk, buyuk);
}



































































































































































































































